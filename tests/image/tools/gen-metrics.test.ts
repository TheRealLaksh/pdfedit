/**
 * Rebuilds src/image/fonts/metrics.data.ts and checks every font address of the image font list.
 * Run:  GEN_METRICS=1 npx vitest run tests/image/tools/gen-metrics.test.ts
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { strokeWidth } from "../../../src/image/analyze/measure";
import { FAMILIES } from "../../../src/image/fonts/catalog";
import { Fonts, outlines, type Shaped } from "../../../src/image/fonts/shape";
import { Coverage } from "../../../src/image/outline";
import { createNodeAssets } from "../../fonts/nodeAssets";

const SAMPLE = "Hamburgefonstiv 0123456789";

describe.skipIf(!process.env.GEN_METRICS)("font metrics", () => {
  it("measures every Latin face", { timeout: 900_000 }, async () => {
    const fonts = new Fonts(createNodeAssets());
    const lines: string[] = [];
    const failed: string[] = [];
    for (const family of FAMILIES) {
      if (!family.scripts.includes("Latin")) {
        for (const weight of family.weights) {
          try {
            const bytes = await fonts.bytes({ font: family.key, weight, italic: false });
            expect(bytes.length).toBeGreaterThan(1000);
          } catch (e) {
            failed.push(`${family.key} ${weight}: ${e}`);
          }
        }
        continue;
      }
      for (const weight of family.weights) {
        const ref = { font: family.key, weight, italic: false };
        try {
          if (family.italic) await fonts.bytes({ ...ref, italic: true });
          const advances: number[] = [];
          for (let code = 32; code < 127; code++) {
            const s = await fonts.shape(ref, `n${String.fromCharCode(code)}`);
            // the position after the character, found by setting an n behind it
            const t = await fonts.shape(ref, `n${String.fromCharCode(code)}n`);
            const last = t.glyphs.at(-1)!;
            const second = s.glyphs.length > 1 ? s.glyphs[1]!.x : last.x;
            advances.push(Math.round((last.x - second) * 10));
          }
          const extent = async (text: string) => (await fonts.shape(ref, text)).ink;
          const cap = -(await extent("H"))[1] * 10;
          const xHeight = -(await extent("x"))[1] * 10;
          const ascender = -(await extent("bdhl"))[1] * 10;
          const descender = (await extent("pq"))[3] * 10;
          const shaped: Shaped = await fonts.shape(ref, SAMPLE);
          const [x0, y0, x1, y1] = shaped.ink;
          const size = 60;
          const scale = size / 100;
          const w = Math.ceil((x1 - x0) * scale) + 4;
          const h = Math.ceil((y1 - y0) * scale) + 4;
          const coverage = new Coverage(w, h);
          for (const g of outlines(shaped, { ox: 2 - x0 * scale, oy: 2 - y0 * scale, size, stretch: 1, spacing: 0, shear: 0 }, 0, (u, v) => [u, v])) coverage.add(g);
          const stem = (strokeWidth(coverage.finish(), w, h) / size) * 1000;
          lines.push(
            `  "${family.key}:${weight}": { cap: ${Math.round(cap)}, xHeight: ${Math.round(xHeight)}, ascender: ${Math.round(ascender)}, descender: ${Math.round(descender)}, stem: ${Math.round(stem * 10) / 10}, advances: [${advances.join(",")}] },`,
          );
        } catch (e) {
          failed.push(`${family.key} ${weight}: ${e}`);
        }
      }
    }
    writeFileSync(
      fileURLToPath(new URL("../../../src/image/fonts/metrics.data.ts", import.meta.url)),
      `/** Generated by tests/image/tools/gen-metrics.test.ts. Per mille of the font size. */
export interface FaceMetrics {
  cap: number;
  xHeight: number;
  ascender: number;
  descender: number;
  /** average stroke thickness, as the editor measures it */
  stem: number;
  /** advance of the characters 32..126 */
  advances: number[];
}

export const METRICS: Record<string, FaceMetrics> = {
${lines.join("\n")}
};
`,
    );
    expect(failed).toEqual([]);
  });
});
