/**
 * Writes src/engine/fonts/metrics.data.ts from the Latin fonts already in .tmp/fonts-cache (nothing is
 * downloaded). Run by hand: METRICS=1 npx vitest run tests/fonts/gen-metrics.test.ts
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { expect, it } from "vitest";
import { FAMILIES } from "../../src/engine/fonts/catalog";
import { loadFace } from "../../src/engine/fonts/face";
import { METRIC_LETTERS } from "../../src/engine/fonts/match";

const cached = (url: string) => `.tmp/fonts-cache/${createHash("sha1").update(url).digest("hex").slice(0, 12)}-${url.split("/").pop()}`;

it.runIf(process.env.METRICS)("writes the metrics table", async () => {
  const rows: string[] = [];
  for (const f of FAMILIES) {
    // general text faces only: handwriting, maths and single script fonts must not stand in by shape
    if (!f.scripts.includes("Latin") || f.category === "script" || /math|symbol|emoji|music|noto-(sans|serif)-./.test(f.key)) continue;
    const variants: string[] = [];
    for (const url of [f.urls.r, f.urls.b]) {
      if (!url || !existsSync(cached(url))) continue;
      const face = await loadFace(new Uint8Array(readFileSync(cached(url))));
      if (!face) continue;
      const widths = [...METRIC_LETTERS].map((c) =>
        Math.round((face.hbFont.glyphHAdvance(face.glyph(c.codePointAt(0)!)) * 1000) / face.info.unitsPerEm),
      );
      variants.push(widths.join(" "));
    }
    if (!variants.length) continue;
    const kind = f.category === "mono" ? "m" : f.category === "serif" ? "s" : "n";
    rows.push(`  ["${f.key}", "${kind}", "${variants[0]}", "${variants[1] ?? ""}"],`);
  }
  expect(rows.length).toBeGreaterThan(10);
  writeFileSync(
    "src/engine/fonts/metrics.data.ts",
    `/**
 * Generated by tests/fonts/gen-metrics.test.ts. Advance widths (thousandths of an em) of the characters in
 * METRIC_LETTERS: [catalog key, n sans / s serif / m mono, regular, bold]
 */
export const METRICS: readonly (readonly [string, "n" | "s" | "m", string, string])[] = [
${rows.join("\n")}
];
`,
  );
});
